"""keys.json -> ImageD11/ipf_keys.py (the colour key table) and test/ipf_oracle.json (MTEX check colours).
Adds the R groups on rhombohedral axes by the obverse basis change ubi_H = T ubi_R."""
from __future__ import print_function, division
import json, sys, pprint
from math import gcd
import numpy as np
from ImageD11 import sym_u
import ipf_ref
CA = ipf_ref.correct_angle

K = json.load(open("keys.json"))
G = K["groups"]

T = np.array([[1, -1, 0], [0, 1, -1], [1, 1, 1]])     # rows: a_H, b_H, c_H in a_R, b_R, c_R
Ti = np.linalg.inv(T)
ADJ = np.round(3 * Ti).astype(int)                    # 3 T^-1, integer
R_GROUPS = {"3": "3R", "-3": "-3R", "321": "32R", "3m1": "3mR", "-3m1": "-3mR"}


def red(v):
    v = [int(x) for x in v]
    d = 0
    for x in v:
        d = gcd(d, abs(x))
    return [x // d for x in v]


def to_r(t):
    if "uvw" in t:
        return {"uvw": red(T.T.dot(t["uvw"]))}
    return {"hkl": red(ADJ.dot(t["hkl"]))}


def r_generators(gens):
    out = []
    for s in gens:
        o = np.round(Ti.dot(sym_u.m_from_string(s)).dot(T)).astype(int)
        assert np.allclose(Ti.dot(sym_u.m_from_string(s)).dot(T), o)
        st = sym_u.m_to_string(o)
        assert (sym_u.m_from_string(st) == o).all()
        out.append(st)
    return out


def opset(gens):
    return frozenset(tuple(np.round(o).astype(int).ravel()) for o in sym_u.generate_group(*gens).group)


def cell_of(g):
    a = np.sqrt(np.diag(g))
    ang = lambda i, j: np.degrees(np.arccos(g[i, j] / a[i] / a[j]))
    return [float(x) for x in a] + [ang(1, 2), ang(0, 2), ang(0, 1)]


table, oracle = {}, {}
for name, g in G.items():
    entry = {"laue": g["laue"], "generators": g["generators"]}
    orc = {"test_cell": g["test_cell"], "check_uvw": g["check_uvw"]}
    for kind in ("tsl", "hsv"):
        entry[kind], orc[kind] = [], []
        for key in g[kind]:
            k = {"views": key["views"], "out_of_screen": key["out_of_screen"],
                 "normals": key["normals"], "hue_ref": key["hue_ref"]}
            if kind == "hsv":
                k["split"] = key["split"]
            entry[kind].append(k)
            # rgb: exact centroid and even-hue integral (ipf_ref, 200000 steps);
            # mtex_rgb: MATLAB (1 deg grid centre for 4 corners, 1000 step integral)
            ipf_ref.correct_angle = lambda *a, **kw: CA(*a, n=200000)
            rgb = ipf_ref.colours(g, kind, key, g["test_cell"], np.array(g["check_uvw"]))
            ipf_ref.correct_angle = CA
            o = {"views": key["views"], "rgb": np.round(rgb, 9).tolist(), "mtex_rgb": key["check_rgb"]}
            orc[kind].append(o)
    table[name], oracle[name] = entry, orc

for h, r in R_GROUPS.items():
    e = table[h]
    gens = r_generators(e["generators"])
    entry = {"laue": {"-3": "-3R", "-3m1": "-3mR"}[e["laue"]], "generators": gens,
             "hexagonal_axes": T.tolist()}
    for kind in ("tsl", "hsv"):
        entry[kind] = []
        for k in e[kind]:
            kr = {"views": k["views"]}
            for f in ("out_of_screen", "hue_ref"):
                kr[f] = to_r(k[f])
            for f in ("normals", "split"):
                if f in k:
                    kr[f] = [to_r(t) for t in k[f]]
            entry[kind].append(kr)
    table[r] = entry
    gh = ipf_ref.cell_metric(G[h]["test_cell"])
    gr = Ti.dot(gh).dot(Ti.T)
    oracle[r] = {"test_cell": cell_of(gr), "from": h,
                 "check_uvw": [list(T.T.dot(u)) for u in G[h]["check_uvw"]],
                 "tsl": oracle[h]["tsl"], "hsv": oracle[h]["hsv"]}

# every group is its own set of operations
sets = {n: opset(e["generators"]) for n, e in table.items()}
assert len(set(sets.values())) == len(sets)
for n, f in [("cubic", "432"), ("hexagonal", "622"), ("trigonal", "321"), ("rhombohedralP", "32R"),
             ("tetragonal", "422"), ("orthorhombic", "222"), ("monoclinic_a", "211"),
             ("monoclinic_b", "121"), ("monoclinic_c", "112"), ("triclinic", "1")]:
    got = frozenset(tuple(np.round(o).astype(int).ravel()) for o in getattr(sym_u, n)().group)
    assert got == sets[f], n

out = sys.argv[1]
with open(out, "w") as f:
    f.write('"""Colour keys of ImageD11.rgb_colors, generated by test/ipf_keys/make_shipped.py from\n'
            "%s.\n\n" % K["source"])
    f.write("Per point group: its Laue group, ITA generators (acting on uvw, as sym_u),\n"
            "and per colour key (tsl, hsv) the views it serves (out-of-screen|east, as MTEX\n"
            "how2plot), the out-of-screen vector, the sector boundary plane normals (N.uvw >= 0),\n"
            "the hue reference and the HSV split planes. Vectors are ('hkl', ...) plane\n"
            "normals or ('uvw', ...) directions. R groups on rhombohedral axes (3R ...)\n"
            "come from the hexagonal axes keys by ubi_H = T.ubi_R, T = [[1,-1,0],[0,1,-1],[1,1,1]];\n"
            'their views name the hexagonal axes.\n"""\n\n')
    def tup(t):
        (b, v), = t.items()
        return (str(b), tuple(int(x) for x in v))
    groups = {}
    for n, e in table.items():
        d = {"laue": str(e["laue"]), "generators": tuple(str(s) for s in e["generators"])}
        if "hexagonal_axes" in e:
            d["hexagonal_axes"] = tuple(tuple(int(x) for x in r) for r in e["hexagonal_axes"])
        for kind in ("tsl", "hsv"):
            d[kind] = []
            for k in e[kind]:
                kk = {"views": tuple(str(v) for v in k["views"]), "out_of_screen": tup(k["out_of_screen"]),
                      "normals": tuple(tup(t) for t in k["normals"]), "hue_ref": tup(k["hue_ref"])}
                if kind == "hsv":
                    kk["split"] = tuple(tup(t) for t in k["split"])
                d[kind].append(kk)
            d[kind] = tuple(d[kind])
        groups[str(n)] = d
    f.write("GROUPS = " + pprint.pformat(groups, width=110) + "\n")
json.dump(oracle, open(sys.argv[2], "w"), separators=(",", ":"))
print(len(table), "groups")
